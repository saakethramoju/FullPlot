"""Read multiple transient operating points from a FullFlow HDF5 file.

Run 0generate_linearization_data.py first, or replace the filename with a
transient linearization file generated by FullFlow.
"""

from pathlib import Path

import fullplot as fplt


example_dir = Path(__file__).resolve().parent
filename = example_dir / "linearization_demo.h5"

file = fplt.open(filename)

final = file.linearization(solver="transient")
print("Final/base operating point:", final.time)
print("Final A:\n", final.A)

points = file.linearization(solver="transient", times=[0.1, 0.3])

for time, linear in points.items():
    print(f"\nTime: {time:g} s")
    print("State labels:", linear.states)
    print("Input labels:", linear.inputs)
    print("A:\n", linear.A)
    print("B:\n", linear.B)

run = file.at("/Tank/linearization/transient/runs/base")
point = run.linearization(time=0.1)
print("\nScoped result at:", point.time)
