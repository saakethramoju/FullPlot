"""Read the matrices and labels of a FullFlow linearization HDF5 file.

Run 0generate_linearization_data.py first, or replace the filename with a
linearization file generated by FullFlow.
"""

from pathlib import Path

import fullplot as fplt


example_dir = Path(__file__).resolve().parent
filename = example_dir / "linearization_demo.h5"

file = fplt.open(filename)
file.linearizations()

steady = file.linearization(solver="steady_state")

print("\nSteady-state linearization")
print("Time:", steady.time)
print("States:", steady.states)
print("Inputs:", steady.inputs)
print("Outputs:", steady.outputs)
print("A:\n", steady.A)
print("B:\n", steady.B)
print("C:\n", steady.C)
print("D:\n", steady.D)
print("Diagnostics:", steady.diagnostics)
